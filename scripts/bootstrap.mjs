import { spawnSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { root, upstream, revision, environment } from './runtime.mjs';

const env = environment();
function run(command, args, cwd = upstream) {
  const result = spawnSync(command, args, { cwd, env, stdio: 'inherit' });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(`${command} failed (${result.status})`);
}
if (!existsSync(join(upstream, '.git'))) {
  mkdirSync(join(root, 'upstream'), { recursive: true });
  run('git', ['clone', '--no-checkout', '--filter=blob:none', 'https://github.com/yctimlin/mcp_excalidraw.git', upstream], root);
  run('git', ['checkout', '--detach', revision]);
}
const head = spawnSync('git', ['rev-parse', 'HEAD'], { cwd: upstream, encoding: 'utf8' });
if (head.stdout.trim() !== revision) throw new Error(`Expected upstream ${revision}; refusing to replace another checkout.`);
const patch = join(root, 'patches/dependency-lock.patch');
const applied = spawnSync('git', ['apply', '--reverse', '--check', patch], { cwd: upstream, stdio: 'ignore' });
if (applied.status !== 0) run('git', ['apply', patch]);
run('npm', ['ci', '--no-fund']);
run('npm', ['run', 'build']);

// Serve Excalidraw's packaged fonts locally before its module initializes.
// Keep upstream source unchanged; repeat this after each production build.
cpSync(join(upstream, 'node_modules/@excalidraw/excalidraw/dist/prod/fonts'),
  join(upstream, 'dist/frontend/fonts'), { recursive: true });
const htmlPath = join(upstream, 'dist/frontend/index.html');
let html = readFileSync(htmlPath, 'utf8');
if (!html.includes('window.EXCALIDRAW_ASSET_PATH')) {
  html = html.replace('<head>', '<head>\n    <script>window.EXCALIDRAW_ASSET_PATH = "/";</script>');
}
writeFileSync(htmlPath, html);

// Machine-specific paths are generated, ignored by Git, and scoped to this project.
mkdirSync(join(root, '.codex'), { recursive: true });
const config = join(root, '.codex/config.toml');
const marker = '# Generated by scripts/bootstrap.mjs';
if (existsSync(config) && !readFileSync(config, 'utf8').startsWith(marker)) {
  throw new Error('Existing .codex/config.toml is user-managed; merge the MCP config manually.');
}
writeFileSync(config, `${marker}\n[mcp_servers.excalidraw_local]\ncommand = ${JSON.stringify(process.execPath)}\nargs = [${JSON.stringify(join(root, 'scripts/whiteboard.mjs'))}, "--mcp"]\ncwd = ${JSON.stringify(root)}\nstartup_timeout_sec = 30\ntool_timeout_sec = 60\ndisabled_tools = ["export_to_excalidraw_url"]\n`);
console.log('Ready. Run npm start, then open http://127.0.0.1:3210.');
